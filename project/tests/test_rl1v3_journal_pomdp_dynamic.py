@pytest.mark.parametrize('mode',['worker_error','timeout'])
def test_transport_preserves_failed_wire_and_timing_without_model(monkeypatch,tmp_path,mode):
    import io
    import time
    import hashlib
    from metacom_pm.rl1v3.journal import pomdp_dynamic_worker as W
    monkeypatch.setattr(W.L,'device_guard',lambda *a,**kw:None)
    monkeypatch.setattr(W.selectors,'DefaultSelector',lambda:SimpleNamespace(
        register=lambda *a:None,select=lambda *a:[],close=lambda:None))
    backend=W.SubprocessDynamicHF(tmp_path,dict(scope_sha256='cpu-scope'),{},tmp_path,time.monotonic()+60)
    backend.p=SimpleNamespace(stdin=io.BytesIO(),stdout=object(),pid=123456,poll=lambda:1)
    response=dict(ok=False,error='synthetic invalid request',failure_stamp=MonotonicClock().stamp())
    raw=json.dumps(response).encode()
    backend.buffer=raw+b'\n' if mode=='worker_error' else b'{"partial_wire":'
    command=dict(operation='generate',request={'request_id':'synthetic'})
    try:
        with pytest.raises(ValueError,match='worker error|hard deadline'):
            backend._exchange(command,10 if mode=='worker_error' else 0)
        path=tmp_path/'WIRE_FAILURE_001.private.json'
        record=json.loads(path.read_text())
        assert record['elapsed_ns']>0 and record['partial_generated_output'] is None
        assert record['first_effective_output'] is None and record['retry_calls']==0
        assert hashlib.sha256(path.read_bytes()).hexdigest()==backend.last_failure['sha256']
        if mode=='worker_error':
            assert record['worker_response']==response and bytes.fromhex(record['raw_response_line_hex'])==raw
        else:
            assert record['worker_response'] is None and record['raw_response_line_hex'] is None
            assert bytes.fromhex(record['buffered_incomplete_wire_hex'])==b'{"partial_wire":'
        assert len(backend.p.stdin.getvalue().splitlines())==1
    finally:backend.global_timer.cancel()
