class Backend:
    kind='cpu_protocol_fixture_not_model'
    scope_sha256='synthetic-eight-task-scope'
    def __init__(self,mode=None):self.counts=Counter();self.sent=[];self.mode=mode
    def generate(self,request,seconds):
        self.sent.append(deepcopy(request));role=request['role'];tid=request['binding']['task_id']
        self.counts[(tid,role)]+=1
        if self.mode=='error':raise RuntimeError('synthetic backend failure')
        if role=='terminal':text='CPU protocol fixture, not generated by a model.'
        else:
            obs=json.loads(request['payload']['messages'][1]['content'])
            if role=='oneshot':
                value=[dict(action='SEARCH',query=obs['query']),dict(action='EXPAND',from_search=0,hit_rank=0),dict(action='STOP')]
            else:
                n=self.counts[(tid,role)]
                value=dict(action='SEARCH',query=obs['query']) if n in (1,3) else dict(action='EXPAND',handle=obs['last_hits'][-1 if n==4 else 0])
            text=json.dumps(value)
            if self.mode=='bad_query':text=json.dumps([dict(action='SEARCH',query='hiddenword')])
            if self.mode=='bad_json':text='```json\n'+text+'\n```'
        ids=[17,1];finish='eos'
        if self.mode=='terminal_length' and role=='terminal' or self.mode=='controller_length' and role!='terminal':
            ids=[17]*request['payload']['decode']['max_new_tokens'];finish='length'
        result=dict(text=text,token_ids=ids,finish_reason=finish,seconds=.01,
            input_tokens=len(request['payload']['input_ids']),request_sha256=object_sha256(request))
        if self.mode=='mismatch':result['request_sha256']='wrong'
        return result


def drive(backend=None,**kwargs):
    events=[];clock=Clock()
    result=execute_source_pair(tasks=tasks(),factory=factory,backend=backend or Backend(),
        emit=lambda e,**kw:events.append(dict(event=e,**kw)),clock=clock,deadline_ns=10**12,**kwargs)
    return result,events


def test_real_tool_state_machine_and_all_22_call_budgets():
    backend=Backend();result,events=drive(backend)
    assert result['status']=='FINISHED' and result['physical_calls']==22
    assert result['calls_by_role']==dict(terminal=12,oneshot=2,agent=8)
    assert len(result['results'])==12 and not result['pending']
    assert all(r['formal_reward'] is None and not r['cache_reused'] for r in result['results'])
    assert all(r['status']=='cpu_fixture_transport_only' and not r['real_model_output']
        and r['backend']==backend.kind for r in result['results'])
    assert sum(e['event']=='TOOL_RETURNED' for e in events)>20
    controls=[e for e in events if e['event']=='CONTROLLER_ACTION_VALIDATED']
    assert len(controls)==8
    agents=[r for r in backend.sent if r['role']=='agent']
    first=json.loads(agents[0]['payload']['messages'][1]['content'])
    second=json.loads(agents[1]['payload']['messages'][1]['content'])
    assert first['hits']==[] and len(second['hits'])==2 and first!=second
    assert 'elapsed' not in json.dumps(first) and 'remaining_time' not in json.dumps(second)
    assert any(e['event']=='FORCED_STOP' for e in events)


