#!/usr/bin/env python3
"""Read-only source assertions; writes only CHECKS.json beside this script.

This checks provenance and preparation structure, not clinical or semantic truth.
"""
import ast
import hashlib
import json
import re
from pathlib import Path

DOC = Path(__file__).resolve().parent
PROJECT = DOC.parents[3]
BASE = PROJECT / 'outputs/pm_rl1/research_preparation_20261115_v1'


def read(path):
    return json.loads(path.read_text())


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def digest(value):
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True,
                                    separators=(',', ':')).encode()).hexdigest()


versions = read(BASE / 'versions/VERSION_REUSE_MANIFEST.json')
for row in versions['source_file_fingerprints']:
    assert sha(Path(row['path'])) == row['sha256'], row['path']

sessions = read(BASE / 'memory/SELECTED_COMPLETE_SESSIONS_PRIVATE.json')
observations = read(BASE / 'memory/SEMANTIC_OBSERVATIONS_PRIVATE.json')
assert len(sessions) == 24
assert len({s['source']['owner_id'] for s in sessions}) == 15
by_id = {s['sample_id']: s for s in sessions}
for s in sessions:
    assert s['split'] in ('train', 'dev')
    assert digest(s['source']) == s['normalized_source_sha256']
    assert s['review_status'] == 'complete_session_read_single_assistant_first_pass'
    for binding in s['legal_prefix_bindings']:
        assert s['source']['session_rank'] < binding['cutoff_rank']
        assert s['source']['reported_at'] <= binding['timestamp']
span_count = 0
for obs in observations:
    s = by_id[obs['sample_id']]
    assert obs['source_sha256'] == s['normalized_source_sha256']
    assert obs['formal_training_label'] is False
    assert obs['causal_effect_established'] is False
    for evidence in obs['evidence']:
        turn = s['source']['turns'][evidence['turn_index']]
        assert turn['role'] == evidence['speaker']
        assert turn['text'][evidence['start_char']:evidence['end_char']] == evidence['quote']
        span_count += 1

cards = [json.loads(line) for line in (BASE / 'rs/case_candidates.jsonl').read_text().splitlines()]
assert len(cards) == len({c['source']['dialogue_id'] for c in cards}) == 12
for card in cards:
    source = card['source']
    assert source['split'] == 'train'
    raw = read(BASE / 'rs' / source['full_source_file'])
    assert digest(raw) == source['dialogue_sha256']
    indices = []
    for field in ('source_context_before_action', 'supporter_action_block', 'observed_next_seeker_block'):
        for turn in card[field]:
            i = turn['turn_index']
            assert {k: v for k, v in turn.items() if k != 'turn_index'} == raw['dialog'][i]
            indices.append(i)
    assert indices == list(range(len(indices)))
    assert all(t['speaker'] == 'supporter' for t in card['supporter_action_block'])
    assert all(t['speaker'] == 'seeker' for t in card['observed_next_seeker_block'])
    assert raw['dialog'][len(card['source_context_before_action']) - 1]['speaker'] == 'seeker'

repairs = read(BASE / 'memory/CANDIDATE_VIEW_REPAIRS_PRIVATE.json')
assert len(repairs) == 3
protected = set()
for repair in repairs:
    old = repair['old_snapshot']
    body = json.loads(old['content'])
    candidate = repair['candidate']
    assert hashlib.sha256(old['content'].encode()).hexdigest() == repair['old_content_sha256']
    assert candidate['source_evidence_unchanged'] == body['evidence']
    assert candidate['current_status'] == 'unknown'
    assert candidate['causal_effect_established'] is False
    assert candidate['formal_training_label'] is False
    assert candidate['candidate_only'] is True
    for binding in repair['old_catalog_bindings']:
        path = PROJECT / binding['source_path']
        assert sha(path) == binding['source_sha256']
        protected.add(str(path))

script_count = 0
for path in BASE.rglob('*.py'):
    ast.parse(path.read_text(), filename=str(path))
    script_count += 1

links = []
for path in DOC.glob('*.md'):
    for target in re.findall(r'\]\(([^)]+)\)', path.read_text()):
        if target.startswith(('http:', 'https:', '#')):
            continue
        target = target.split('#', 1)[0]
        if not target:
            continue
        destination = (path.parent / target).resolve()
        # CHECKS is being generated by this invocation.
        assert destination.exists() or destination == DOC / 'CHECKS.json', (path, target)
        links.append({'from': path.name, 'target': target})

result = {
    'status': 'PASS_OFFLINE_PREPARATION_INVARIANTS',
    'source_file_hashes_rechecked': len(versions['source_file_fingerprints']),
    'memory_sessions': len(sessions), 'memory_owners': 15,
    'assistant_source_observations': len(observations), 'exact_quote_spans': span_count,
    'rs_candidates': len(cards), 'candidate_memory_repairs': len(repairs),
    'historical_catalog_files_unchanged': len(protected),
    'preparation_scripts_syntax_checked': script_count,
    'local_document_links_checked': len(links), 'broken_local_links': 0,
    'semantic_review': 'single assistant source review; not independent human gold',
    'not_established': ['whole-corpus extraction recall', 'expert method applicability',
                        'new resource benefit', 'qualified natural-support reward',
                        'final prefix/evaluation freeze', 'unexposed confirmation set',
                        'production integration'],
    'execution': {'new_G_J_embedding_calls': 0, 'training_updates': 0,
                  'new_paid_calls': 0, 'production_code_changes': 0},
    'artifact_hashes': {str(p.relative_to(BASE)): sha(p) for p in sorted(BASE.rglob('*'))
                        if p.is_file() and '__pycache__' not in p.parts},
    'document_hashes': {p.name: sha(p) for p in sorted(DOC.glob('*.md'))},
}
(DOC / 'CHECKS.json').write_text(json.dumps(result, ensure_ascii=False, indent=2) + '\n')
print(json.dumps({k: v for k, v in result.items()
                  if k not in ('artifact_hashes', 'document_hashes')}, ensure_ascii=False, indent=2))
